const ingestionResult = executeIngestionPipeline(RAW_STAGING_INGREDIENTS);

export const CANONICAL_INGREDIENTS_DATABASE: CanonicalIngredient[] = ingestionResult.processed;

/**
 * Searches canonical repository by exact INCI, CAS number, or registered alternative name/synonym.
 */
export function findCanonicalIngredient(query: string): CanonicalIngredient | undefined {
  if (!query || query.trim().length === 0) return undefined;
  const upper = query.trim().toUpperCase();

  // 1. Exact canonical INCI match
  const exactInci = CANONICAL_INGREDIENTS_DATABASE.find(i => i.inciName === upper);
  if (exactInci) return exactInci;

  // 2. CAS number match
  const byCas = CANONICAL_INGREDIENTS_DATABASE.find(i => i.casNumber === upper);
  if (byCas) return byCas;

  // 3. Exact common name or synonym match
  const bySynonym = CANONICAL_INGREDIENTS_DATABASE.find(i => 
    i.commonNames.some(cn => cn.toUpperCase() === upper) ||
    i.synonyms.some(s => s.toUpperCase() === upper)
  );
  if (bySynonym) return bySynonym;

  // 4. Substring containment
  return CANONICAL_INGREDIENTS_DATABASE.find(i =>
    i.inciName.includes(upper) ||
    upper.includes(i.inciName) ||
    i.synonyms.some(s => upper.includes(s.toUpperCase()))
  );
}
